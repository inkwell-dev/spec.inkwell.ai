#!/usr/bin/env python3
"""Merge the split global figures into one global use case diagram and one
complete class diagram.

Chapter 1 shows the global use cases in three parts (by actor) and the classes
in five parts (by domain), so each stays readable at page width. This script
merges those parts into one source each, so the whole picture can be shown too
without a second copy of the content to keep in step:

  fig-1-3/4/5 use case parts  →  fig-1-11-use-case-global/…puml
  fig-1-6…10 class parts      →  fig-1-12-classes-global/…puml

The use case aliases are prefixed per part: the parts were written separately
and reuse names (EDIT is "Edit one's profile" in one, "Edit a draft" in
another). Actors keep their names, so they merge. A class that appears in
several parts (User, Article) gets the union of its members, in order of first
appearance.

  python3 gen-global-figures.py      # then: python3 gen-use-cases.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

UC_PARTS = [('V', 'fig-1-3-use-case-visitor-reader'),
            ('W', 'fig-1-4-use-case-writer'),
            ('M', 'fig-1-5-use-case-magazine-admin')]
CLASS_PARTS = ['fig-1-6-classes-accounts-articles', 'fig-1-7-classes-social',
               'fig-1-8-classes-ai-documents', 'fig-1-9-classes-marketplace',
               'fig-1-10-classes-analytics']
UC_OUT = 'fig-1-11-use-case-global'
CLASS_OUT = 'fig-1-12-classes-global'

UC_NOTE = """note as N1
  Every use case of the Reader, the Writer, the Magazine and the
  Administrator includes «Sign in».
  The assistant needs the premium plan: «Consume the AI allowance»
  has the condition [plan = premium].
  The administrator role is granted in the database, never through
  the interface.
end note"""


def read(name):
    with open(os.path.join(ROOT, name, f'{name}.puml')) as f:
        return f.read().splitlines()


def write(name, text):
    os.makedirs(os.path.join(ROOT, name), exist_ok=True)
    with open(os.path.join(ROOT, name, f'{name}.puml'), 'w') as f:
        f.write(text)
    print(f'wrote {name}.puml')


def merge_use_cases():
    actors, cases, rels = {}, [], []
    gens = []
    for tag, part in UC_PARTS:
        local = {}                                          # alias → prefixed alias
        lines = read(part)
        for line in lines:
            s = line.strip()
            if m := re.match(r'actor "(.+?)" as (\w+)$', s):
                actors.setdefault(m[2], s)
            elif m := re.match(r'usecase "(.+?)" as (\w+)$', s):
                local[m[2]] = f'{tag}_{m[2]}'
                cases.append(f'  usecase "{m[1]}" as {tag}_{m[2]}')
        for line in lines:
            s = line.strip()
            m = re.match(r'^(\w+)\s+(\S+)\s+(\w+)(\s*:.*)?$', s)
            if not m or m[1] in ('actor', 'usecase', 'note', 'skinparam', 'rectangle'):
                continue
            a, op, b, label = m[1], m[2], m[3], m[4] or ''
            if a in actors and b in actors:
                if s not in gens:
                    gens.append(s)
                continue
            rels.append(f'{local.get(a, a)} {op} {local.get(b, b)}{label}')
    body = ['@startuml',
            "' Global use case diagram, all actors: generated by",
            "' tools/gen-global-figures.py from fig-1-3, fig-1-4 and fig-1-5. Edit those.",
            '!include ../_style.puml',
            *actors.values(), *gens,
            'rectangle "Inkwell.ai" {', *cases, '}',
            *rels, UC_NOTE, '@enduml', '']
    write(UC_OUT, '\n'.join(body))


def merge_classes():
    classes, order, rels = {}, [], []
    heads = {}
    for part in CLASS_PARTS:
        lines = read(part)
        i = 0
        while i < len(lines):
            s = lines[i].strip()
            if m := re.match(r'class (\w+)( <<\w+>>)? \{$', s):
                name = m[1]
                heads.setdefault(name, s)
                if name not in classes:
                    classes[name] = []; order.append(name)
                i += 1
                while lines[i].strip() != '}':
                    member = lines[i].rstrip()
                    if member.strip() and member not in classes[name]:
                        classes[name].append(member)
                    i += 1
            elif re.match(r'^\w+ ("[^"]*" )?--', s) and 'hidden' not in s:
                if s not in rels:
                    rels.append(s)
            i += 1
    # Operations after attributes, whichever part contributed them.
    for name in order:
        attrs = [m for m in classes[name] if '(' not in m]
        ops = [m for m in classes[name] if '(' in m]
        classes[name] = attrs + ops
    plain = [n for n in order if '<<Enumeration>>' not in heads[n]]
    enums = [n for n in order if '<<Enumeration>>' in heads[n]]
    body = ['@startuml',
            "' Complete class diagram: generated by tools/gen-global-figures.py",
            "' from fig-1-6 … fig-1-10. Edit those.",
            '!include ../_style.puml',
            '!pragma layout elk',
            'hide circle',
            'hide empty methods', '']
    for n in plain + enums:
        body += [heads[n], *classes[n], '}']
    body += [''] + rels + ['@enduml', '']
    write(CLASS_OUT, '\n'.join(body))


if __name__ == '__main__':
    merge_use_cases()
    merge_classes()
