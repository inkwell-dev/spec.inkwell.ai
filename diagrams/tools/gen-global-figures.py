#!/usr/bin/env python3
"""Merge the split class figures into one complete class diagram.

Chapter 1 shows the classes in five parts (by domain), so each stays readable at
page width. This script merges those parts into one source, so the whole picture
can be shown too without a second copy of the content to keep in step:

  fig-1-6…10 class parts      →  fig-1-12-classes-global/…puml

A class that appears in several parts (User, Article) gets the union of its
members, in order of first appearance.

The global use case diagram (fig-1-11) used to be merged here from fig-1-3/4/5
too. It is now laid out by hand in draw.io after the supervisor's review, and its
.puml is kept in step with the drawing by hand, so this script no longer writes it.

  python3 gen-global-figures.py      # then: python3 gen-class-global.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

CLASS_PARTS = ['fig-1-6-classes-accounts-articles', 'fig-1-7-classes-social',
               'fig-1-8-classes-ai-documents', 'fig-1-9-classes-marketplace',
               'fig-1-10-classes-analytics']
CLASS_OUT = 'fig-1-12-classes-global'


def read(name):
    with open(os.path.join(ROOT, name, f'{name}.puml')) as f:
        return f.read().splitlines()


def write(name, text):
    os.makedirs(os.path.join(ROOT, name), exist_ok=True)
    with open(os.path.join(ROOT, name, f'{name}.puml'), 'w') as f:
        f.write(text)
    print(f'wrote {name}.puml')


def merge_classes():
    classes, order, rels = {}, [], []
    heads = {}
    for part in CLASS_PARTS:
        lines = read(part)
        i = 0
        while i < len(lines):
            s = lines[i].strip()
            if m := re.match(r'class (\w+)( <<\w+>>)? \{$', s):
                name = m[1]
                heads.setdefault(name, s)
                if name not in classes:
                    classes[name] = []; order.append(name)
                i += 1
                while lines[i].strip() != '}':
                    member = lines[i].rstrip()
                    if member.strip() and member not in classes[name]:
                        classes[name].append(member)
                    i += 1
            elif re.match(r'^\w+ ("[^"]*" )?--', s) and 'hidden' not in s:
                if s not in rels:
                    rels.append(s)
            i += 1
    # Operations after attributes, whichever part contributed them.
    for name in order:
        attrs = [m for m in classes[name] if '(' not in m]
        ops = [m for m in classes[name] if '(' in m]
        classes[name] = attrs + ops
    plain = [n for n in order if '<<Enumeration>>' not in heads[n]]
    enums = [n for n in order if '<<Enumeration>>' in heads[n]]
    body = ['@startuml',
            "' Complete class diagram: generated by tools/gen-global-figures.py",
            "' from fig-1-6 … fig-1-10. Edit those.",
            '!include ../_style.puml',
            '!pragma layout elk',
            'hide circle',
            'hide empty methods', '']
    for n in plain + enums:
        body += [heads[n], *classes[n], '}']
    body += [''] + rels + ['@enduml', '']
    write(CLASS_OUT, '\n'.join(body))


if __name__ == '__main__':
    merge_classes()
